// Turns a backup downloaded from /api/export into SQL for a freshly migrated D1 database.
//
//   node scripts/import-backup.mjs golf3d-backup-2026-11-05.json > import.sql
//   pnpm exec wrangler d1 execute golf3d --remote --file import.sql
//
// The database already enforces money rules with triggers (open shift required, payment amounts
// must equal the booking, immutable ledgers...). Replaying history row by row would trip them, so
// the generated script drops every trigger, inserts the rows exactly as exported, then recreates
// the triggers from the migrations. Run it ONLY on an empty database that has all migrations.
import { readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { unstable_splitSqlQuery } from 'wrangler';
import { literal, quoteIdent } from './sql-util.mjs';

// Parents before children (foreign keys are enforced by D1).
export const IMPORT_ORDER = [
  'settings',
  'shifts',
  'bookings',
  'requests',
  'audit',
  'finance_entries',
  'menu_items',
  'food_orders',
  'stock_items',
  'stock_movements',
  'customers',
  'package_types',
  'customer_packages',
  'package_ledger',
  'package_redemptions',
  'loyalty_ledger',
  'booking_requests',
  'coaches',
  'lessons',
];

export function triggerDefinitions(root = resolve(import.meta.dirname, '..')) {
  const db = new DatabaseSync(':memory:');
  const dir = resolve(root, 'drizzle');
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort())
    for (const statement of unstable_splitSqlQuery(readFileSync(resolve(dir, file), 'utf8')))
      db.exec(statement);
  const rows = db
    .prepare("SELECT name,sql FROM sqlite_master WHERE type='trigger' ORDER BY rowid")
    .all();
  db.close();
  return rows;
}

export function buildImportSql(backup, triggers = triggerDefinitions()) {
  if (backup?.format !== 'golf3d-export/1' || typeof backup.data !== 'object')
    throw new Error('Not a golf3d-export/1 file');
  const unknown = Object.keys(backup.data).filter((t) => !IMPORT_ORDER.includes(t));
  if (unknown.length) throw new Error('Unknown tables in backup: ' + unknown.join(', '));
  const out = [
    '-- Generated by scripts/import-backup.mjs. Run once on an empty, fully migrated database.',
    ...triggers.map((t) => `DROP TRIGGER IF EXISTS ${quoteIdent(t.name)};`),
  ];
  const counts = {};
  for (const table of IMPORT_ORDER) {
    const rows = backup.data[table] ?? [];
    counts[table] = rows.length;
    for (const row of rows) {
      const columns = Object.keys(row);
      out.push(
        `INSERT INTO ${quoteIdent(table)}(${columns.map(quoteIdent).join(',')}) VALUES (${columns.map((c) => literal(row[c])).join(',')});`,
      );
    }
  }
  out.push(...triggers.map((t) => t.sql.trimEnd().replace(/;?$/, ';')));
  return { sql: out.join('\n') + '\n', counts };
}

if (
  import.meta.url === `file://${process.argv[1].replaceAll('\\', '/')}` ||
  process.argv[1]?.endsWith('import-backup.mjs')
) {
  const file = process.argv[2];
  if (!file) throw new Error('Usage: node scripts/import-backup.mjs <backup.json>');
  const { sql, counts } = buildImportSql(JSON.parse(readFileSync(file, 'utf8')));
  process.stdout.write(sql);
  console.error('Rows:', JSON.stringify(counts));
}
